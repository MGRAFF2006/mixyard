#!/usr/bin/env bash
set -euo pipefail
# OFFLINE recipe. The caller supplies reviewed artifacts. Never builds Rust,
# installs an SDK, connects to a server, or runs the resulting executable.
: "${MIXYARD_PRIVATE_PREFIX:?canonical absolute reviewed PipeWire 1.4.8 prefix}"
: "${MIXYARD_HOST_LIBRARY:?absolute prebuilt actual libmixyard_host.a}"
: "${MIXYARD_HOST_SHA256:?reviewed SHA256 of that exact host archive}"
: "${MIXYARD_PRIVATE_BUILD:?fresh owned output directory under /dev/shm}"
here=$(cd -- "$(dirname -- "$0")" && pwd)
root=$(cd -- "$here/../../.." && pwd)
python3 -B "$here/resource_guard.py" --forecast 2097152 --output "$MIXYARD_PRIVATE_BUILD"
python3 -B - "$MIXYARD_PRIVATE_PREFIX" "$MIXYARD_HOST_LIBRARY" "$MIXYARD_HOST_SHA256" "$MIXYARD_PRIVATE_BUILD" <<'PY'
import hashlib, os, pathlib, re, sys
prefix, archive, expected, output = sys.argv[1:]
p, a, out = map(pathlib.Path, (prefix, archive, output))
if not p.is_absolute() or p.resolve(strict=True) != p or not p.is_dir():
    raise SystemExit("canonical absolute SDK prefix required")
if not a.is_absolute() or a.is_symlink() or a.name != "libmixyard_host.a" or not a.is_file():
    raise SystemExit("explicit regular actual libmixyard_host.a required")
if not re.fullmatch("[a-f0-9]{64}", expected):
    raise SystemExit("explicit reviewed host SHA256 required")
h = hashlib.sha256()
with a.open("rb") as f:
    for block in iter(lambda: f.read(65536), b""):
        h.update(block)
if h.hexdigest() != expected:
    raise SystemExit("host archive hash mismatch")
if out.exists() and any(out.iterdir()):
    raise SystemExit("output must be fresh and empty; no shared target or cleanup")
out.mkdir(mode=0o700, exist_ok=True)
PY
# PKG_CONFIG_LIBDIR replaces the system search path. json-c must be explicitly
# supplied too; a system package is not silently used as an SDK fallback.
: "${MIXYARD_JSON_C_PC_DIR:?explicit directory holding reviewed json-c.pc}"
pc_dirs=()
while IFS= read -r -d '' pc; do pc_dirs+=("$(dirname -- "$pc")"); done < <(find "$MIXYARD_PRIVATE_PREFIX" -name libpipewire-0.3.pc -type f -print0)
[[ ${#pc_dirs[@]} == 1 ]] || { echo 'exactly one prefix PipeWire pkg-config file required' >&2; exit 2; }
export PKG_CONFIG_PATH=
export PKG_CONFIG_LIBDIR="${pc_dirs[0]}:$MIXYARD_JSON_C_PC_DIR"
[[ $(pkg-config --modversion libpipewire-0.3) == 1.4.8 ]] || { echo 'reviewed experimental 1.4.8 SDK required' >&2; exit 2; }
[[ $(realpath -- "$(pkg-config --variable=prefix libpipewire-0.3)") == "$MIXYARD_PRIVATE_PREFIX" ]] || { echo 'pkg-config prefix mismatch' >&2; exit 2; }
export TMPDIR="$MIXYARD_PRIVATE_BUILD"
read -r -a native_cflags <<< "$(pkg-config --cflags libpipewire-0.3 json-c)"
read -r -a native_libs <<< "$(pkg-config --libs libpipewire-0.3 json-c)"
"${CXX:-c++}" -std=gnu++17 -O2 -g0 -Wall -Wextra -Werror -Wno-missing-field-initializers \
  -ffunction-sections -fdata-sections -Wl,--gc-sections -s \
  "${native_cflags[@]}" -I"$root/adapters/engine/include" \
  "$here/companion.cpp" "$MIXYARD_HOST_LIBRARY" "${native_libs[@]}" \
  -pthread -ldl -lm -lrt -lutil -o "$MIXYARD_PRIVATE_BUILD/mixyard-private-companion"
python3 -B - "$MIXYARD_PRIVATE_BUILD" <<'PY'
from pathlib import Path
import sys
files = [p for p in Path(sys.argv[1]).rglob("*") if p.is_file()]
total = sum(p.stat().st_size for p in files)
if total > 2 * 1024**2:
    raise SystemExit(f"generated artifact budget exceeded: {total} bytes; preserve for inspection, do not prune")
print(f"offline executable built, NOT RUN: {files[0].parent}; generated bytes={total}")
PY
