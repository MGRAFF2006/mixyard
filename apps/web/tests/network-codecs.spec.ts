test('real workspace retains hidden target drafts and discards stale fixture capability after session revision, switch and revocation', async ({ page }) => {
  await open(page, true); const p = panel(page)
  expect(await page.evaluate(() => window.codecHarness.hasUnsaved())).toBe(false)
  await fillIds(page); await p.getByRole('button', { name: 'Bind for capability reads' }).click()
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await expect(p.getByText('Fixture qualification only.', { exact: false })).toBeVisible()
  await expect(p.getByText('Agreement: receive-admitted.')).toBeVisible()
  await expect(p.getByText('Unknown: Fixture does not measure Linux thread CPU')).toBeVisible()
  await expect(p.getByText('18446744073709551000.', { exact: false })).toBeVisible()
  await p.getByText('Expert constraints, budgets and provenance', { exact: true }).click()
  await expect(p.locator('pre').filter({ hasText: 'private-call' })).toBeVisible()
  await p.getByRole('heading', { name: 'Network stream codecs', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/network-codecs-desktop.png' })
  await page.evaluate(() => window.codecHarness.advance())
  await expect(p.getByText('Fixture qualification only.', { exact: false })).not.toBeVisible()
  await expect(p.getByRole('button', { name: 'Probe exact intent' })).toBeDisabled()
  await p.getByRole('button', { name: 'Bind for capability reads' }).click()
  await page.evaluate(() => window.codecHarness.hold())
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await expect(p.getByRole('button', { name: 'Reading capability…' })).toBeDisabled()
  await p.getByRole('button', { name: 'Cancel capability read' }).click()
  await page.evaluate(() => window.codecHarness.release())
  await expect(p.getByText('Fixture qualification only.', { exact: false })).not.toBeVisible()
  await page.evaluate(() => window.codecHarness.hold())
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await page.getByLabel('Manage device', { exact: true }).selectOption('B')
  expect(await page.evaluate(() => window.codecHarness.hasUnsaved())).toBe(true)
  await page.getByRole('button', { name: 'Network codecs', exact: true }).click()
  await expect(p.getByLabel('Stream ID', { exact: true })).toHaveValue('')
  await p.getByLabel('Stream ID', { exact: true }).fill('[invalid-array-draft]')
  await page.evaluate(() => window.codecHarness.release())
  await page.getByLabel('Manage device', { exact: true }).selectOption('A')
  await expect(p.getByLabel('Stream ID', { exact: true })).toHaveValue(rawIntent.streamId)
  await expect(p.getByText('Fixture qualification only.', { exact: false })).not.toBeVisible()
  await expect(p.getByRole('button', { name: 'Probe exact intent' })).toBeDisabled()
  await p.getByRole('button', { name: 'Bind for capability reads' }).click()
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await expect(p.getByText('Fixture qualification only.', { exact: false })).toBeVisible()
  await page.evaluate(() => window.codecHarness.disconnect())
  await expect(p.getByText('Fixture qualification only.', { exact: false })).not.toBeVisible()
  await expect(p.getByRole('button', { name: 'Bind for capability reads' })).toBeDisabled()
  await expect(p.getByRole('button', { name: 'Apply to live stream' })).toBeDisabled()
  expect(await page.evaluate(() => !window.dispatchEvent(new Event('beforeunload', { cancelable: true })))).toBe(true)
})

