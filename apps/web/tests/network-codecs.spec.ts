import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { rawIntent } from './network-codec-fixture.ts'
const panel = (page: Page) => page.getByRole('region', { name: 'Network stream codecs', exact: true })
async function open(page: Page, fixture = false) {
  await page.route('**/api/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":{"code":"unavailable","message":"No codec service in browser qualification"}}' }))
  await page.goto('/')
  if (fixture) await page.evaluate(async () => { const entry = '/tests/network-codec-harness.ts'; (await import(entry)).mount() })
  await page.getByRole('button', { name: 'Network codecs', exact: true }).click()
  await expect(panel(page)).toBeVisible()
}
async function fillIds(page: Page) { await panel(page).getByLabel('Stream ID', { exact: true }).fill(rawIntent.streamId); await panel(page).getByLabel('Generation', { exact: true }).fill(rawIntent.generation) }
async function downloaded(page: Page, name: string): Promise<unknown> {
  const pending = page.waitForEvent('download'); await panel(page).getByRole('button', { name, exact: true }).click()
  return JSON.parse(readFileSync((await (await pending).path())!, 'utf8'))
}

test('actual console edits full-u64 intent offline, rejects ambiguous imports, and restores invalid fields without authority', async ({ page }) => {
  await open(page); const p = panel(page)
  await expect(p.getByText('No host capability connection.', { exact: false })).toBeVisible()
  await expect(p.getByRole('button', { name: 'Apply to live stream' })).toBeDisabled()
  await fillIds(page); expect(await downloaded(page, 'Export valid intent')).toEqual(rawIntent)
  await p.getByLabel('Encoding intent').selectOption('opus')
  await expect(p.getByRole('button', { name: 'Export valid intent' })).toBeDisabled()
  await p.getByLabel('I allow lossy conversion', { exact: false }).check()
  await p.getByLabel('Opus bitrate', { exact: false }).fill('64000')
  expect(await downloaded(page, 'Export valid intent')).toEqual({ ...rawIntent, allowLossy: true, encoding: { mode: 'opus', bitrate: 64000, complexity: 5, vbr: true, conversion: 'normalized-f32-clamp-v1' } })
  await p.getByLabel('Opus bitrate', { exact: false }).fill('6000.00000000000001')
  await p.getByRole('button', { name: 'Add stream draft', exact: true }).click()
  await p.getByLabel('Stream draft', { exact: true }).selectOption('1')
  await expect(p.getByLabel('Opus bitrate', { exact: false })).toHaveValue('6000.00000000000001')
  await p.getByText('Import portable intent or restore unfinished drafts', { exact: true }).click()
  const ambiguous = JSON.stringify(rawIntent).replace('"version":1', '"version":1,"version":1')
  await p.getByLabel('Codec JSON', { exact: true }).fill(ambiguous)
  await p.getByRole('button', { name: 'Import intent', exact: true }).click()
  await expect(p.getByRole('alert')).toContainText('Duplicate JSON field')
  await expect(p.getByLabel('Codec JSON', { exact: true })).toHaveValue(ambiguous)
  const backup = await downloaded(page, 'Export all draft text')
  expect(JSON.stringify(backup)).not.toContain('authorityId')
  await p.getByLabel('Codec JSON', { exact: true }).fill(JSON.stringify(backup))
  await p.getByRole('button', { name: 'Restore draft backup', exact: true }).click()
  await expect(p.getByLabel('Codec JSON', { exact: true })).toHaveValue(ambiguous)
  await expect(p.getByLabel('Stream draft', { exact: true }).locator('option')).toHaveCount(4)
  await p.getByLabel('Stream draft', { exact: true }).selectOption('3')
  await expect(p.getByLabel('Opus bitrate', { exact: false })).toHaveValue('6000.00000000000001')
  await expect(p.getByRole('button', { name: 'Probe exact intent' })).toBeDisabled()
  await p.getByLabel('Load codec JSON file', { exact: true }).setInputFiles({ name: 'exact-intent.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(rawIntent)) })
  await expect(p.getByLabel('Codec JSON', { exact: true })).toHaveValue(JSON.stringify(rawIntent))
  await p.getByRole('button', { name: 'Import intent', exact: true }).click()
  expect(await downloaded(page, 'Export valid intent')).toEqual(rawIntent)
  await expect(p.getByLabel('Stream draft', { exact: true }).locator('option')).toHaveCount(5)
  expect(await page.evaluate(() => !window.dispatchEvent(new Event('beforeunload', { cancelable: true })))).toBe(true)
})

test('raw and Zstd cannot export or probe lossy consent, and invalid imported consent stays reviewable', async ({ page }) => {
  await open(page, true); const p = panel(page)
  await fillIds(page); await p.getByRole('button', { name: 'Bind for capability reads' }).click()
  await p.getByLabel('I allow lossy conversion', { exact: false }).check()
  for (const mode of ['raw', 'zstd']) {
    await p.getByLabel('Encoding intent').selectOption(mode)
    await expect(p.getByRole('button', { name: 'Export valid intent' })).toBeDisabled()
    await expect(p.getByRole('button', { name: 'Probe exact intent' })).toBeDisabled()
    await expect(p.getByText('Raw and Zstd require allowLossy: false.', { exact: false })).toBeVisible()
  }
  expect(await page.evaluate(() => window.codecHarness.calls.length)).toBe(0)
  await p.getByLabel('I allow lossy conversion', { exact: false }).uncheck()
  expect(await downloaded(page, 'Export valid intent')).toEqual({ ...rawIntent, encoding: { mode: 'zstd', level: 1 } })
  await p.getByText('Import portable intent or restore unfinished drafts', { exact: true }).click()
  const invalid = JSON.stringify({ ...rawIntent, allowLossy: true })
  await p.getByLabel('Codec JSON', { exact: true }).fill(invalid)
  await p.getByRole('button', { name: 'Import intent', exact: true }).click()
  await expect(p.getByRole('alert')).toContainText('Raw and Zstd require allowLossy: false')
  await expect(p.getByLabel('Codec JSON', { exact: true })).toHaveValue(invalid)
})

