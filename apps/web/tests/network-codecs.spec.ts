test('probe errors and exact unavailable reasons keep input and allow explicit retry without enabling apply', async ({ page }) => {
  await open(page, true); const p = panel(page)
  await fillIds(page); await p.getByLabel('Encoding intent').selectOption('zstd')
  await p.getByLabel('Zstd level (1–3)', { exact: true }).fill('3')
  await p.getByRole('button', { name: 'Bind for capability reads' }).click()
  await page.evaluate(() => window.codecHarness.mode('error'))
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await expect(p.getByRole('alert')).toContainText('Fixture capability service unavailable')
  await expect(p.getByLabel('Zstd level (1–3)', { exact: true })).toHaveValue('3')
  await page.evaluate(() => window.codecHarness.mode('unavailable'))
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await expect(p.getByRole('heading', { name: 'Exact plan unavailable', exact: true })).toBeVisible()
  await expect(p.getByText('Exact codec/consent not granted by this fixture', { exact: true })).toBeVisible()
  await expect(p.getByRole('button', { name: 'Apply to live stream' })).toBeDisabled()
  await page.evaluate(() => window.codecHarness.mode('fixture'))
  await p.getByRole('button', { name: 'Probe exact intent' }).click()
  await expect(p.getByRole('heading', { name: 'Fixture reports an available plan', exact: true })).toBeVisible()
  await expect(p.getByRole('button', { name: 'Apply to live stream' })).toBeDisabled()
})
