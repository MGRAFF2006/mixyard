// Test-only TLV construction lets malformed inputs reach the ACTUAL adapter.
// No fixture builder, key generation or signing is part of the shipping target.
private func tlv(_ tag: UInt8, _ value: [UInt8]) -> [UInt8] {
    let length = value.count < 128 ? [UInt8(value.count)] : value.count < 256
        ? [0x81, UInt8(value.count)] : [0x82, UInt8(value.count >> 8), UInt8(value.count & 255)]
    return [tag] + length + value
}
private func sequence(_ values: [[UInt8]]) -> [UInt8] { tlv(0x30, values.flatMap { $0 }) }
private let sha256 = sequence([[6,8,42,134,72,206,61,4,3,2]])
private let ecPublicKey: [UInt8] = [6,7,42,134,72,206,61,2,1]
private let p256: [UInt8] = [6,8,42,134,72,206,61,3,1,7]
private func encodeName(_ text: String) -> [UInt8] {
    sequence([tlv(0x31, sequence([[6,3,85,4,3], tlv(0x0c, Array(text.utf8))]))])
}
private struct Fixture {
    let key: SecKey
    var version = tlv(0xa0, [2,1,2])
    var serial: [UInt8] = [2,1,1]
    var inner = sha256
    var outer = sha256
    var issuer = encodeName("Owned canonical fixture")
    var subject = encodeName("Owned canonical fixture")
    var keyAlgorithm = sequence([ecPublicKey, p256])
    var keyBits: [UInt8] = []
    var suffix: [[UInt8]] = []
    init(bits: Int = 256) throws {
        key = try XCTUnwrap(SecKeyCreateRandomKey([
            kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom, kSecAttrKeySizeInBits as String: bits
        ] as CFDictionary, nil))
        let publicKey = try XCTUnwrap(SecKeyCopyPublicKey(key))
        keyBits = [0] + Array(try XCTUnwrap(SecKeyCopyExternalRepresentation(publicKey, nil)) as Data)
    }
    func tbs() -> [UInt8] {
        sequence([version, serial, inner, issuer,
            sequence([tlv(0x17, Array("240101000000Z".utf8)), tlv(0x17, Array("490101000000Z".utf8))]),
            subject, sequence([keyAlgorithm, tlv(3, keyBits)])] + suffix)
    }
    func certificate(signature: [UInt8]? = nil, signatureTag: UInt8 = 3, padding: UInt8 = 0,
                     extra: [[UInt8]] = []) throws -> Data {
        let message = tbs()
        let signed = try XCTUnwrap(SecKeyCreateSignature(key, .ecdsaSignatureMessageX962SHA256, Data(message) as CFData, nil)) as Data
        return Data(sequence([message, outer, tlv(signatureTag, [padding] + (signature ?? Array(signed)))] + extra))
    }
}

final class CanonicalControlCertificateTests: XCTestCase {
    func testValidCanonicalOriginalTLVAndBothPositiveIntegerWidths() throws {
        // Distinct signatures/lengths are generated by Security, never normalized.
        for _ in 0..<8 { try CanonicalControlCertificate.verify(Fixture().certificate()) }
        var large = try Fixture()
        large.subject = encodeName(String(repeating: "a", count: 60)); large.issuer = large.subject
        try CanonicalControlCertificate.verify(large.certificate())
    }
    func testEveryTruncationAndRootLengthBoundaryRejects() throws {
        let valid = try Fixture().certificate()
        for end in 0..<valid.count {
            XCTAssertThrowsError(try CanonicalControlCertificate.verify(valid.prefix(end)), "truncation offset \(end)")
        }
        let malformed: [[UInt8]] = [Array(valid)+[0], [0x30,0x80,0,0], [0x30,0x81,0],
            [0x30,0x82,0,0x80]+Array(repeating:0,count:128), [0x30,0x89]+Array(repeating:255,count:9),
            [0x30,0x82,0xff,0xff], Array(repeating:0,count:65537)]
        for bytes in malformed {
            XCTAssertThrowsError(try CanonicalControlCertificate.verify(Data(bytes)))
        }
        let fixture = try Fixture()
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(fixture.certificate(extra:[[5,0]])))
    }
    func testAlgorithmsParametersCurveAndKeyAreBoundNotGuessed() throws {
        var f = try Fixture()
        f.outer = sequence([[6,8,42,134,72,206,61,4,3,3]]) // ECDSA SHA384
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.inner = sequence([[6,8,42,134,72,206,61,4,3,2],[5,0]])
        f.outer = f.inner // Matching but forbidden NULL parameters, correctly signed TBS.
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.inner = sequence([[6,3,42,3,4]]); f.outer = f.inner
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        for oid in [tlv(0x26,[6,8,42,134,72,206,61,4,3,2]),
                    [6,9,0x80,42,134,72,206,61,4,3,2], [6,1,0x80]] {
            f = try Fixture(); f.inner = sequence([oid]); f.outer = f.inner
            XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        }
        f = try Fixture(); f.keyAlgorithm = sequence([ecPublicKey])
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.keyAlgorithm = sequence([ecPublicKey,p256,[5,0]])
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(bits:384); f.keyAlgorithm = sequence([ecPublicKey,[6,5,43,129,4,0,34]])
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.keyAlgorithm = sequence([[6,9,42,134,72,134,247,13,1,1,1],p256])
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.keyBits[0] = 1
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.keyBits = [0,4]
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
    }
    func testSignatureEncodingAndPlatformCryptographicRangeRejects() throws {
        let f = try Fixture()
        let one: [UInt8] = [2,1,1]
        let malformedIntegers: [[UInt8]] = [[2,0], [2,1,0], [2,1,0x80], [2,1,0xff], [2,2,0,1],
            [2,2,0xff,0xff], tlv(2,[1]+Array(repeating:0,count:32)), tlv(0x22,[2,1,1])]
        for integer in malformedIntegers {
            for pair in [[integer,one],[one,integer]] {
                XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate(signature:sequence(pair))))
            }
        }
        for signature in [[], [0x30,0], sequence([one]), sequence([one,one,one]),
                          sequence([tlv(2,[0]+Array(repeating:255,count:32)),one]), sequence([one,one])+[0]] {
            XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate(signature:signature)))
        }
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate(signatureTag:0x23)))
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate(padding:1)))
        var corrupt = Array(try f.certificate()); corrupt[corrupt.count-1] ^= 1
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(Data(corrupt))) // Matching public/private key, invalid self-signature.
    }
    func testCanonicalProfileNamesFieldsAndParserDepthRejects() throws {
        var f = try Fixture(); f.subject = encodeName("Different normalized subject")
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.subject = [0x30,0]; f.issuer = f.subject
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.version = tlv(0xa0,[2,1,1])
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.serial = [2,1,0]
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.suffix = [[5,0]]
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        f = try Fixture(); f.suffix = [tlv(0xa3,sequence([])),[5,0]]
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
        var nested: [UInt8] = [5,0]
        for _ in 0..<55 { nested = sequence([nested]) }
        f = try Fixture(); f.suffix = [tlv(0xa3,nested)]
        XCTAssertThrowsError(try CanonicalControlCertificate.verify(f.certificate()))
    }
}
